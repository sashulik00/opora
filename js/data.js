/* Заготовка теста, пока нет настоящих вопросов: placeholderQuiz(10) — 10 вопросов-заглушек.
   Когда будете писать настоящий тест, замените в теме quiz: placeholderQuiz(10)
   на свой список вопросов в таком формате:
     quiz: [
       {
         question: "Текст вопроса?",
         options: ["Вариант 1", "Вариант 2", "Вариант 3"],
         correct: 0,                          // номер верного варианта: 0 — первый, 1 — второй…
         explanation: "Почему так (необязательно)"
       },
       ...
     ],
   Варианты на странице теста перемешиваются сами — правильный можно писать на любом месте. */
function placeholderQuiz(count) {
  count = count || 3;
  const questions = [];
  for (let i = 1; i <= count; i++) {
    questions.push({
      question: "Вопрос " + i + " — текст-заглушка?",
      options: ["Вариант А", "Вариант Б", "Вариант В"],
      correct: (i - 1) % 3,
      explanation: "Пояснение-заглушка к вопросу " + i + "."
    });
  }
  return questions;
}

