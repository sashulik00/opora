/* Температура 39 и выше: «температура 39,5», «39.8 градусов», «t 40» */
const ALARM_PATTERNS = [
  /(температур\S*|\bt\b|жар)\D{0,12}(39|4[0-2])([.,]\d)?(?!\d)/,
  /(?<![\d.,])(39|4[0-2])([.,]\d)?\s*(градус|°)/
];

function normalize(text) {
  return String(text || "").toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ");
}

function hasAlarm(text) {
  const t = normalize(text);
  return ALARM_PHRASES.some(function (p) { return t.indexOf(p) !== -1; }) ||
    ALARM_PATTERNS.some(function (re) { return re.test(t); });
}

const ALARM_ANSWER = "Это может быть опасно. Немедленно звоните 103 или 112.";

module.exports = { hasAlarm, ALARM_ANSWER };
